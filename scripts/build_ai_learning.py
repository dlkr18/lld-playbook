def build(units, labs):
    import whiteboards                                    # scripts/whiteboards.py
    boards = whiteboards.render_all(AI / "img")           # name -> caption
    cards = json.loads((ROOT / "scripts" / "ai_topic_cards.json").read_text(encoding="utf-8"))
    used, order, moved = set(), [], {}
    topic_of = {}
    unit_topic, unit_title = {}, {}        # handbook chapter id -> "stage/slug", topic title
    for folder, stitle, _, tlist in STAGES:
        for t in tlist:
            for u in t[3]:
                if u.startswith("hb:"):
                    unit_topic[u[3:]] = f"{folder}/{t[0]}"
                    unit_title[u[3:]] = t[1]
    title_of = {}
    stage_title = {f: t for f, t, _, _ in STAGES}
    for folder, stitle, _, tlist in STAGES:
        for t in tlist:
            order.append((folder, stitle) + t)
            title_of[f"{folder}/{t[0]}"] = t[1]
            for u in t[3]:
                if u.startswith("ts:"):
                    topic_of[u[3:]] = f"{folder}/{t[0]}"

    collected = []
    for i, (folder, stitle, slug, title, desc, ids) in enumerate(order):
        glance, ref, body, tail, qa, builds, has_lab, seen = [], [], [], [], [], [], False, set()
        deep = depth_unit(slug)
        sheets = [u for u in ids if u.startswith("ts:")]

        def add(target, lab, inner):
            sid, k = slugify(lab) or "section", 2
            while sid in seen:
                sid, k = f"{slugify(lab)}-{k}", k + 1
            seen.add(sid)
            target.append((sid, lab, inner))

        for uid in ids:
            assert uid not in used, f"{uid} used twice"
            used.add(uid)
            if uid.startswith("ts:"):
                key = uid[3:]
                u = sheet_unit(key, topic_of)
                glance += u["glance"]
                prefix = cards[key]["title"] + ": " if len(sheets) > 1 else ""
                for lab, inner in u["sections"]:
                    add(tail if WRAP_UP.search(lab) else ref, prefix + lab, inner)
                qa += u["qa"]
                moved[key] = f"../{folder}/{slug}.html"
            elif uid.startswith("wb:"):
                name = uid[3:]
                assert name in boards, f"no whiteboard named {name}"
                glance.append(f'<div class="diagram"><img src="../img/{name}.png" alt="{esc(boards[name])}"></div>'
                              f'<p class="diagram-caption">{esc(boards[name])}</p>')
            else:
                assert uid in units, f"unknown unit {uid}"
                has_lab |= uid in labs
                if uid.startswith("qa:"):
                    qa += units[uid]
                elif uid.startswith("build:"):
                    if units[uid]:
                        builds.append(units[uid])
                else:
                    for lab, inner in units[uid]:
                        add(body, "Recap" if lab.strip().lower() == title.lower() else lab, inner)

        lesson = []
        if deep:                                   # hand-written teaching comes first on the page
            for lab, inner in deep["sections"]:
                add(lesson, lab, inner)
            qa[:0] = deep["qa"]
            if deep["lost"]:
                add(tail, "Where people get lost", deep["lost"])
        # one "Where people get lost" section: the sheet's pitfalls and the lesson's, together
        lost = [x for x in tail if re.search(r"pitfall|where people get lost", x[1], re.I)]
        if len(lost) > 1 or (lost and lost[0][1] != "Where people get lost"):
            merged = "\n".join(x[2] for x in lost)
            tail = [x for x in tail if x not in lost] + [("where-people-get-lost", "Where people get lost", merged)]

        for img, cap in EXTRA_DIAGRAMS.get(slug, []):
            assert (AI / img).exists(), img
            glance.append(f'<div class="diagram"><img src="../{img}" alt="{esc(cap)}"></div>'
                          f'<p class="diagram-caption">{esc(cap)}</p>')
        sections = []
        if glance:
            sections.append(("at-a-glance", "At a glance", "\n".join(glance)))
        # the lesson, then the cheat sheet, then the source depth, then production notes and pitfalls;
        # a divider names each block once the page has more than one
        blocks = [(b, lab) for b, lab in ((lesson, "The lesson"), (ref, "Quick reference"),
                                          (body, "More detail" if lesson else "The full explanation"),
                                          (tail, "In production")) if b]
        for b, lab in blocks:
            if len(blocks) > 1:
                sections.append((None, lab, None))
            sections += b
        if qa:
            sections.append(("check-yourself", "Check yourself", "\n".join(qa)))
        if builds:
            sections.append(("build-it", "Build it", "".join(f'<div class="callout success">{b}</div>' for b in builds)))

        def resolve(h, here=folder, me=slug):
            h = re.sub(r"@@T:(\w+)@@", lambda m: unit_title[m.group(1)], h)
            h = re.sub(r"@@TT:([\w-]+/[\w-]+)@@", lambda m: title_of.get(m.group(1), stage_title.get(m.group(1).split("/")[0], "")), h)
            h = re.sub(r'href="@@hb:(\w+)@@"', lambda m: f'href="@@{unit_topic[m.group(1)]}@@"', h)
            h = re.sub(r'href="@@([^/@]+)/([^@]+)@@"',
                       lambda m: f'href="{m.group(2) if m.group(1) == here else "../" + m.group(1) + "/" + m.group(2)}.html"', h)
            return h
        sections = [(sid, resolve(lab), resolve(inner) if inner else inner) for sid, lab, inner in sections]
        # related-topic lists: current titles, no self-links, no duplicates
        fixed = []
        for sid, lab, inner in sections:
            if sid is None:
                fixed.append((sid, lab, inner))
                continue
            if "data-retitle" in inner:
                frag = BeautifulSoup(inner, "html.parser")
                for a in frag.find_all("a", attrs={"data-retitle": True}):
                    key = a["data-retitle"]
                    if key in title_of and a.get_text(strip=True):
                        a.string = title_of[key]
                    del a["data-retitle"]
                inner = str(frag)
            if lab.endswith("Related topics"):
                frag = BeautifulSoup(inner, "html.parser")
                seen_h = set()
                for a in frag.find_all("a", href=True):
                    h = a["href"].split("#")[0]
                    tgt = (h[:-5] if "/" not in h else h.split("/")[-2] + "/" + h.split("/")[-1][:-5]) if h.endswith(".html") else None
                    key = tgt if tgt and "/" in tgt else (f"{folder}/{tgt}" if tgt else None)
                    li = a.find_parent("li") or a
                    if key == f"{folder}/{slug}" or key in seen_h:
                        li.decompose()
                        continue
                    seen_h.add(key)
                    if key in title_of:
                        a.string = title_of[key]
                inner = str(frag)
            fixed.append((sid, lab, inner))
        sections = fixed
        collected.append({"i": i, "folder": folder, "stitle": stitle, "slug": slug, "title": title,
                          "desc": desc, "sections": sections, "has_lab": has_lab,
                          "words": deep["words"] if deep else []})

    # ---- second pass: things that need the whole map
    key_of = lambda c: f"{c['folder']}/{c['slug']}"
    pos = {key_of(c): c["i"] for c in collected}
    desc_of = {key_of(c): c["desc"] for c in collected}

    def links_from(c):
        out = set()
        for _, _, inner in c["sections"]:
            for h in re.findall(r'href="([^"#:]+\.html)', inner or ""):
                parts = h.split("/")
                k = f"{parts[-2]}/{parts[-1][:-5]}" if len(parts) > 1 else f"{c['folder']}/{h[:-5]}"
                if k in pos and k != key_of(c):
                    out.add(k)
        return out
    out_links = {key_of(c): links_from(c) for c in collected}
    in_links = {k: {src for src, outs in out_links.items() if k in outs} for k in pos}

    # glossary terms: each lives on the topic that uses it most
    gloss = []
    g = BeautifulSoup("".join(x[1] for x in units.get("hb:c91", [])), "html.parser")
    for tr in g.find_all("tr"):
        td = tr.find_all("td")
        if len(td) == 2:
            gloss.append((td[0].get_text(strip=True), td[1].decode_contents().strip()))
    text_of = {key_of(c): BeautifulSoup(" ".join(x[2] or "" for x in c["sections"]), "html.parser").get_text(" ")
               for c in collected}
    home = {}
    for term, meaning in gloss:
        alts = [a.strip() for a in term.split("/") if a.strip()]
        pats = [re.compile(r"\b" + re.escape(a) + r"\b", 0 if a.isupper() else re.I) for a in alts]
        counts = {k: sum(len(p.findall(t)) for p in pats) for k, t in text_of.items() if not k.endswith("/glossary")}
        best = max(counts, key=lambda k: (counts[k], -pos[k]))
        if counts[best]:
            home.setdefault(best, []).append((term, meaning))

    for c in collected:
        k = key_of(c)
        folder = c["folder"]
        rel_href = lambda t: f"{t.split('/')[1]}.html" if t.split("/")[0] == folder else f"../{t}.html"
        sections = list(c["sections"])
        # New words: hand-written rows first, then the glossary terms that live here
        rows = list(c["words"]) + [(esc(t), m) for t, m in home.get(k, [])
                                   if t.lower() not in {BeautifulSoup(w, "html.parser").get_text().lower() for w, _ in c["words"]}]
        if rows and not k.endswith("/glossary"):
            table = ("<table><thead><tr><th>Word</th><th>Meaning</th></tr></thead><tbody>" +
                     "".join(f"<tr><td><strong>{w}</strong></td><td>{m}</td></tr>" for w, m in rows) +
                     "</tbody></table>")
            at = 1 if sections and sections[0][0] == "at-a-glance" else 0
            sections.insert(at, ("new-words", "New words", table))
        # how this topic connects to the rest of the map
        before = sorted((t for t in out_links[k] if pos[t] < pos[k]), key=pos.get)[:6]
        later = sorted((t for t in in_links[k] if pos[t] > pos[k]), key=pos.get)[:8]
        if before or later:
            li = lambda t: f'<li><a href="{rel_href(t)}">{esc(title_of[t])}</a> &mdash; {esc(desc_of[t])}</li>'
            html_c = ""
            if before:
                html_c += "<h3>Builds on</h3><ul>" + "".join(li(t) for t in before) + "</ul>"
            if later:
                html_c += "<h3>Where this shows up later</h3><ul>" + "".join(li(t) for t in later) + "</ul>"
            at = next((j for j, x in enumerate(sections) if x[0] in ("check-yourself", "build-it")), len(sections))
            sections.insert(at, ("how-this-connects", "How this connects", html_c))
        words = sum(len(BeautifulSoup(x[2] or "", "html.parser").get_text(" ").split()) for x in sections)
        n_diag = sum((x[2] or "").count('class="diagram"') for x in sections)
        tags = [f"{max(1, round(words / 230))} min read"] + ([f"{n_diag} diagram{'s' if n_diag > 1 else ''}"] if n_diag else [])
        math = any(("\\(" in (x[2] or "") or "\\[" in (x[2] or "")) for x in sections)
        scripts = (("../ai-math.js",) if math else ()) + (("../ai-labs.js",) if c["has_lab"] else ()) + ("../ai-progress.js",)
        i = c["i"]
        prev = order[i - 1] if i else None
        nxt = order[i + 1] if i + 1 < len(order) else None
        rel = lambda t: (f"../{t[0]}/{t[2]}.html" if t[0] != folder else f"{t[2]}.html", t[3])
        html_ = page(title=c["title"], h1=c["title"], qualifier=c["stitle"], lead=esc(c["desc"]), tags=tags,
                     sections=sections, back=("index.html", c["stitle"]),
                     pager=(rel(prev) if prev else None, rel(nxt) if nxt else None),
                     scripts=scripts, math=math)
        html_ = html_.replace("</title>", f'</title>\n<meta name="ai-stage" content="{esc(c["stitle"])}" data-href="index.html">'
                              f'\n<meta name="ai-topic" content="{k}">', 1)
        (AI / folder).mkdir(exist_ok=True)
        (AI / folder / f"{c['slug']}.html").write_text(html_, encoding="utf-8")

    leftover = sorted(u for u in units if u not in used and units[u])
    assert not leftover, f"source units not on the map: {leftover}"
    unplaced = set(cards) - set(moved)
    assert not unplaced, f"cheat sheets not merged: {unplaced}"
    assert not set(EXTRA_DIAGRAMS) - {t[2] for t in order}, "EXTRA_DIAGRAMS names a topic not on the map"
    unused = set(boards) - {u[3:] for u in used if u.startswith("wb:")}
    assert not unused, f"whiteboards drawn but unused: {unused}"

    current = {AI / f / f"{t[0]}.html" for f, _, _, tl in STAGES for t in tl}
    for f in AI.glob("*/*.html"):
        if f not in current and f.name != "index.html" and \
                "generated by scripts/build_ai_learning.py" in f.read_text(encoding="utf-8"):
            f.unlink()

    # stage pages: topics only
    for n, (folder, stitle, sdesc, tlist) in enumerate(STAGES, 1):
        groups = [("Topics", [(f"{s}.html", t, d, []) for s, t, d, _ in tlist])]
        if n < len(STAGES):
            nf, nt, nd, _ = STAGES[n]
            groups.append(("Next stage", [(f"../{nf}/index.html", f"{n + 1:02d} · {nt}", nd, [])]))
        (AI / folder / "index.html").write_text(hub(
            title=f"{stitle} — AI",
            crumbs=[("../../index.html", "Cheat Sheets"), ("../index.html", "AI"), ("", stitle)],
            h1=f"{n:02d} · {stitle}", h1_span="", subtitle=esc(sdesc),
            stat=(len(tlist), "topics"), groups=groups), encoding="utf-8")

    n_topics = len(order)
    stage_cards = "".join(
        f'\n    <a href="{f}/index.html" class="sub-card" data-stage="{f}" data-topics="{" ".join(f + "/" + x[0] for x in tl)}">'
        f'<h3>{n:02d} &middot; {esc(t)}</h3><p>{esc(d)}</p>'
        f'<div class="count">{len(tl)} topics</div></a>'
        for n, (f, t, d, tl) in enumerate(STAGES, 1))
    (AI / "index.html").write_text(f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>AI Cheat Sheets</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;700&family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../shared.css">
<script>(function(){{try{{if(localStorage.getItem("playbook-theme")==="dark")document.documentElement.setAttribute("data-theme","dark");}}catch(e){{}}}})();</script>
</head>
<body class="theme-ai">
<!-- generated by scripts/build_ai_learning.py -->
<nav class="site-nav"><div class="site-nav-inner"><span class="spacer"></span></div></nav>
<div class="container">
  <div class="breadcrumbs"><a href="../index.html">Cheat Sheets</a><span>/</span> AI</div>
  <header class="page-header"><h1>AI / LLMs / <span>Agents</span></h1>
  <p class="subtitle">One map from first principles to a shipped agent. Work through the stages in order. Every topic is one page: a diagram at a glance, a step-by-step lesson with worked numbers and code, the quick reference, and questions to check yourself.</p>
  <div class="stats"><span class="stat"><strong>{len(STAGES)}</strong> stages</span><span class="stat"><strong>{n_topics}</strong> topics</span></div></header>
  <div class="sub-grid">{stage_cards}
  </div></div><script src="../hub.js" defer></script>
<script src="ai-progress.js" defer></script>
<script src="../../theme.js"></script>
</body></html>
""", encoding="utf-8")

    # old addresses keep working: cheat sheets and retired tier indexes redirect
    for key, target in moved.items():
        tier = key.split("/")[0]
        if target == f"../{key}.html":       # the topic page took over this exact path
            continue
        (AI / tier).mkdir(exist_ok=True)
        (AI / f"{key}.html").write_text(REDIRECT.format(t=esc(cards[key]["title"]), u=target), encoding="utf-8")
    stage_folders = {s[0] for s in STAGES}
    for gone in ("systems", "handbook", "courses"):
        d = AI / gone
        d.mkdir(exist_ok=True)
        if gone not in stage_folders:
            (d / "index.html").write_text(REDIRECT.format(t="AI", u="../index.html"), encoding="utf-8")
    return n_topics, len(moved), len(boards)


def main():
    import sys
    sys.path.insert(0, str(ROOT / "scripts"))
    ap = argparse.ArgumentParser()
    ap.add_argument("--handbook", required=True)
    ap.add_argument("--ground-up", required=True)
    ap.add_argument("--evals", required=True)
    a = ap.parse_args()
    units = handbook_units(Path(a.handbook).expanduser())
    gu, gu_labs = course_units(Path(a.ground_up).expanduser(), "gu")
    ev, ev_labs = course_units(Path(a.evals).expanduser(), "ev")
    units.update(gu)
    units.update(ev)
    topics, sheets, boards = build(units, gu_labs | ev_labs)
    print(f"{len(STAGES)} stages · {topics} topics · {sheets} cheat sheets merged · {boards} whiteboards · "
          f"{len(units)} source units")


if __name__ == "__main__":
    main()
