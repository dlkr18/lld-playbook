def js_array(src, name):
    """Pull `const NAME = [...]` / `{...}` out of the page script by bracket
    matching, then let node turn the JS literal into JSON."""
    start = re.search(r"const " + name + r"\s*=\s*", src).end()
    depth, k, quote = 0, start, None
    while True:
        ch = src[k]
        if quote:
            if ch == "\\":
                k += 1
            elif ch == quote:
                quote = None
        elif ch in "'\"`":
            quote = ch
        elif ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    out = subprocess.run(["node", "-e", "process.stdout.write(JSON.stringify(" + src[start:k + 1] + "))"],
                         capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def convert_handbook_body(soup, sec):
    # tabs -> headed blocks (no JS on a cheat sheet)
    tabs = sec.select_one("div.tabs")
    if tabs:
        labels = [b.get_text() for b in tabs.find_all("button")] or \
                 [t.get_text() for t in tabs.select(".tab")]
        level = "h2" if not sec.find("h2") else "h3"
        panes = sec.select("div.tabpane")
        for lab, pane in zip(labels, panes):
            h = soup.new_tag(level)
            h.string = clean(lab)
            pane.insert_before(h)
            pane.unwrap()
        tabs.decompose()
    for sel in ("div.eyebrow", "h1.ch", "p.lead", "footer", "button", "input", "label"):
        for n in sec.select(sel):
            n.decompose()
    for n in sec.select("span.em"):
        n.decompose()
    for n in sec.select("span.anal"):
        n.name = "em"
        del n["class"]
    # code blocks: filename header + highlighted pre
    for cw in sec.select("div.codewrap"):
        fn = cw.select_one(".fn")
        lang = cw.select_one(".lang")
        pre = cw.find("pre")
        syntax(pre)
        highlight(soup, pre, lang.get_text().strip().lower() if lang else "")
        block = soup.new_tag("div", attrs={"class": "code-block"})
        head = soup.new_tag("div", attrs={"class": "code-file"})
        name = soup.new_tag("span")
        name.string = fn.get_text() if fn else ""
        head.append(name)
        if lang:
            lg = soup.new_tag("span", attrs={"class": "code-lang"})
            lg.string = lang.get_text()
            head.append(lg)
        block.append(head)
        block.append(pre.extract())
        cw.replace_with(block)
    for pre in sec.find_all("pre"):
        if "diagram" in (pre.get("class") or []):
            pre["class"] = ["ascii-diagram"]
        elif not pre.find_parent(class_="code-block"):
            syntax(pre)
    for t in sec.select("table"):
        t.attrs = {}
    # callout boxes
    for box in sec.select("div.box"):
        kinds = [c for c in box["class"] if c != "box"]
        kind = CALLOUT.get(kinds[0], "") if kinds else ""
        bt = box.select_one(".bt")
        title = clean(bt.get_text()) if bt else ""
        ib = box.select_one(".ib")
        box.replace_with(callout(soup, kind, title, ib.contents if ib else []))
    # card grids -> tiles
    for g in sec.select("div.grid"):
        g["class"] = ["tile-grid"]
        for c in g.select("div.card"):
            c["class"] = ["tile"]
    for h in sec.find_all(["h2", "h3", "h4"]):
        txt = clean(h.get_text())
        h.clear()
        h.append(txt)
    for n in sec.find_all(class_=True):
        n["class"] = [c for c in n["class"] if c not in ("wide", "g2", "g3", "on")]
        if not n["class"]:
            del n["class"]


def split_sections(soup, sec, level):
    """Split top-level children at <level> headings into (id, label, html)."""
    sections, cur_label, cur = [], None, []
    used = set()

    def flush():
        inner = "".join(str(n) for n in cur).strip()
        if inner:
            label = cur_label or "Overview"
            sid = slugify(label) or "section"
            base, k = sid, 2
            while sid in used:
                sid, k = f"{base}-{k}", k + 1
            used.add(sid)
            sections.append((sid, label, inner))

    for node in list(sec.children):
        if getattr(node, "name", None) == level:
            flush()
            cur_label = re.sub(r"^\d+\s*·\s*", "", node.get_text().strip())
            cur = []
        else:
            cur.append(node)
    flush()
    return sections


def build_handbook(src):
    raw = Path(src).read_text(encoding="utf-8")
    script = re.findall(r"<script>(.*?)</script>", raw, re.S)[-1]
    gloss, check = js_array(script, "G"), js_array(script, "CK")
    soup = BeautifulSoup(raw, "html.parser")
    out_dir = AI / "handbook"
    out_dir.mkdir(exist_ok=True)

    chapters, part_idx = [], {}
    for sec in soup.select("section.page"):
        part = html.unescape(sec["data-part"])
        m = re.match(r"(\d+)\s*·\s*(.*)", part)
        pnum, pname = (int(m.group(1)), m.group(2)) if m else (0, part)
        part_idx[pnum] = part_idx.get(pnum, 0) + 1
        num = f"{pnum}.{part_idx[pnum]}"
        title = html.unescape(sec["data-title"])
        h1 = sec.select_one("h1.ch")
        lead = sec.select_one("p.lead")
        chapters.append({
            "sec": sec, "id": sec["id"], "num": num, "pnum": pnum, "pname": pname,
            "title": title, "h1": clean(h1.get_text()) if h1 else title,
            "lead": lead.decode_contents().strip() if lead else "",
            "file": f"{pnum}-{part_idx[pnum]}-{slugify(title)}.html",
        })

    for i, ch in enumerate(chapters):
        sec = ch["sec"]
        if ch["id"] == "c91":                      # glossary: data lived in JS
            rows = "".join(f"<tr><td><strong>{esc(t)}</strong></td><td>{esc(d)}</td></tr>" for t, d in gloss)
            sections = [("terms", f"{len(gloss)} terms",
                         f"<table><thead><tr><th>Term</th><th>Meaning</th></tr></thead><tbody>{rows}</tbody></table>")]
        elif ch["id"] == "c92":                    # learning path: data lived in JS
            convert_handbook_body(soup, sec)
            key = "".join(str(n) for n in sec.select("div.callout"))
            li = lambda items: "<ol>" + "".join(f"<li><strong>{esc(a)}</strong> &mdash; {esc(b)}</li>" for a, b in items) + "</ol>"
            sections = [("read", "Read (primary sources first)", li(check["ck1"])),
                        ("build", "Build (where the real learning is)", li(check["ck2"]) + key)]
        else:
            convert_handbook_body(soup, sec)
            level = "h2" if sec.find("h2") else "h3"
            sections = split_sections(soup, sec, level)
        prev = chapters[i - 1] if i else None
        nxt = chapters[i + 1] if i + 1 < len(chapters) else None
        (out_dir / ch["file"]).write_text(page(
            title=ch["title"], h1=ch["h1"], qualifier=ch["num"],
            lead=ch["lead"] or esc(ch["title"]),
            tags=[f"Part {ch['pnum']} · {ch['pname']}", f"Chapter {ch['num']}"],
            sections=sections, back=("index.html", "Handbook contents"),
            pager=((prev["file"], f"{prev['num']} {prev['title']}") if prev else None,
                   (nxt["file"], f"{nxt['num']} {nxt['title']}") if nxt else None)),
            encoding="utf-8")

    groups, by_part = [], {}
    for ch in chapters:
        by_part.setdefault((ch["pnum"], ch["pname"]), []).append(ch)
    for (pnum, pname), chs in by_part.items():
        heading = pname if pnum == 0 else f"Part {pnum} · {pname}"
        groups.append((heading, [(c["file"], f"{c['num']} {c['title']}",
                                  re.sub(r"<[^>]+>", "", html.unescape(c["lead"])) or c["h1"],
                                  []) for c in chs]))
    (out_dir / "index.html").write_text(hub(
        title="The LLM & Agents Handbook — AI",
        crumbs=[("../../index.html", "Cheat Sheets"), ("../index.html", "AI"), ("", "Handbook")],
        h1="The LLM & Agents", h1_span="Handbook",
        subtitle="From tokens to production agents: math and ML foundations, LLM internals, prompting, RAG, "
                 "tools, agents, multi-agent systems, fine-tuning and RLHF/DPO, inference, voice agents, "
                 "frameworks, production architecture, and one complete system built end to end.",
        stat=(len(chapters), "chapters"), groups=groups),
        encoding="utf-8")
    return {c["id"]: c for c in chapters}


