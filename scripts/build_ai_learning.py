def slugify(text):
    text = re.sub(r"&[a-z]+;", " ", text.lower())
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")[:60].rstrip("-")


def clean(text):
    return EMOJI.sub("", text).strip()


def esc(text):
    return html.escape(text, quote=True)


