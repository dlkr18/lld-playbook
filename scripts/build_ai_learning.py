EMOJI = re.compile(
    "[\U0001F000-\U0001FAFF☀-➿⬀-⯿️‍⃣]+\\s*")
SYNTAX = {"s": "st", "k": "kw", "c": "cm", "n": "nr", "f": "fn", "t": "tp"}
