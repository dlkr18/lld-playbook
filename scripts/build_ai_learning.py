def js_array(src, name):
    """Pull `const NAME = [...]` / `{...}` out of the page script by bracket
    matching, then let node turn the JS literal into JSON."""
    start = re.search(r"const " + name + r"\s*=\s*", src).end()
    depth, k, quote = 0, start, None
    while True:
        ch = src[k]
        if quote:
            if ch == "\\":
                k += 1
            elif ch == quote:
                quote = None
        elif ch in "'\"`":
            quote = ch
        elif ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    out = subprocess.run(["node", "-e", "process.stdout.write(JSON.stringify(" + src[start:k + 1] + "))"],
                         capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def convert_handbook_body(soup, sec):
    # tabs -> headed blocks (no JS on a cheat sheet)
    tabs = sec.select_one("div.tabs")
    if tabs:
        labels = [b.get_text() for b in tabs.find_all("button")] or \
                 [t.get_text() for t in tabs.select(".tab")]
        level = "h2" if not sec.find("h2") else "h3"
        panes = sec.select("div.tabpane")
        for lab, pane in zip(labels, panes):
            h = soup.new_tag(level)
            h.string = clean(lab)
            pane.insert_before(h)
            pane.unwrap()
        tabs.decompose()
    for sel in ("div.eyebrow", "h1.ch", "p.lead", "footer", "button", "input", "label"):
        for n in sec.select(sel):
            n.decompose()
    for n in sec.select("span.em"):
        n.decompose()
    for n in sec.select("span.anal"):
        n.name = "em"
        del n["class"]
    # code blocks: filename header + highlighted pre
    for cw in sec.select("div.codewrap"):
        fn = cw.select_one(".fn")
        lang = cw.select_one(".lang")
        pre = cw.find("pre")
        syntax(pre)
        highlight(soup, pre, lang.get_text().strip().lower() if lang else "")
        block = soup.new_tag("div", attrs={"class": "code-block"})
        head = soup.new_tag("div", attrs={"class": "code-file"})
        name = soup.new_tag("span")
        name.string = fn.get_text() if fn else ""
        head.append(name)
        if lang:
            lg = soup.new_tag("span", attrs={"class": "code-lang"})
            lg.string = lang.get_text()
            head.append(lg)
        block.append(head)
        block.append(pre.extract())
        cw.replace_with(block)
    for pre in sec.find_all("pre"):
        if "diagram" in (pre.get("class") or []):
            pre["class"] = ["ascii-diagram"]
        elif not pre.find_parent(class_="code-block"):
            syntax(pre)
    for t in sec.select("table"):
        t.attrs = {}
    # callout boxes
    for box in sec.select("div.box"):
        kinds = [c for c in box["class"] if c != "box"]
        kind = CALLOUT.get(kinds[0], "") if kinds else ""
        bt = box.select_one(".bt")
        title = clean(bt.get_text()) if bt else ""
        ib = box.select_one(".ib")
        box.replace_with(callout(soup, kind, title, ib.contents if ib else []))
    # card grids -> tiles
    for g in sec.select("div.grid"):
        g["class"] = ["tile-grid"]
        for c in g.select("div.card"):
            c["class"] = ["tile"]
    for h in sec.find_all(["h2", "h3", "h4"]):
        txt = clean(h.get_text())
        h.clear()
        h.append(txt)
    for n in sec.find_all(class_=True):
        n["class"] = [c for c in n["class"] if c not in ("wide", "g2", "g3", "on")]
        if not n["class"]:
            del n["class"]


def split_sections(soup, sec, level):
    """Split top-level children at <level> headings into (id, label, html)."""
    sections, cur_label, cur = [], None, []
    used = set()

    def flush():
        inner = "".join(str(n) for n in cur).strip()
        if inner:
            label = cur_label or "Overview"
            sid = slugify(label) or "section"
            base, k = sid, 2
            while sid in used:
                sid, k = f"{base}-{k}", k + 1
            used.add(sid)
            sections.append((sid, label, inner))

    for node in list(sec.children):
        if getattr(node, "name", None) == level:
            flush()
            cur_label = re.sub(r"^\d+\s*·\s*", "", node.get_text().strip())
            cur = []
        else:
            cur.append(node)
    flush()
    return sections


def convert_course_nodes(soup, nodes, links):
    holder = soup.new_tag("div")
    for n in nodes:
        holder.append(n.extract())
    for f in holder.select("span.f"):
        f.name = "pre"
        f["class"] = ["formula"]
    for t in holder.select("div.trap"):
        b = t.find("b")
        title = b.get_text().rstrip(":") if b else "Trap"
        if b:
            b.decompose()
        t.replace_with(callout(soup, "warn", title, t.contents))
    for tw in holder.select("div.tw"):
        tw.unwrap()
    for p in holder.select("p.k"):
        del p["class"]
    for pre in holder.find_all("pre"):
        if "formula" not in (pre.get("class") or []):
            for code in pre.find_all("code"):
                code.unwrap()
            text = pre.get_text()
            highlight(soup, pre, "sql" if re.match(r"\s*(--|WITH|SELECT)\b", text) else "python")
    for a in holder.find_all("a", href=True):
        for prefix, target in links.items():
            if a["href"].startswith(prefix):
                a["href"] = target(a["href"][len(prefix):])
                del a["target"]
                del a["rel"]
    return holder.decode_contents().strip()



