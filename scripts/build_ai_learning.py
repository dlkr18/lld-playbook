def callout(soup, kind, title, inner_nodes):
    div = soup.new_tag("div", attrs={"class": ("callout " + kind).strip()})
    if title:
        p = soup.new_tag("p")
        b = soup.new_tag("strong")
        b.string = title
        p.append(b)
        div.append(p)
    for n in list(inner_nodes):
        div.append(n.extract() if hasattr(n, "extract") else n)
    return div


def highlight(soup, pre, lang):
    """Colour a plain code block with the site's six frozen syntax classes.
    The sources ship code uncoloured; Pygments does the tokenising."""
    if pre.find("span") or lang not in ("python", "bash", "json", "sql", "yaml"):
        return
    from pygments import lex
    from pygments.lexers import get_lexer_by_name
    from pygments.token import Comment, Keyword, Literal, Name, Number, String
    def cls(tok):
        if tok in Comment:
            return "cm"
        if tok in String or tok in Literal.String:
            return "st"
        if tok in Number or tok in Keyword.Constant:
            return "nr"
        if tok in Keyword.Type or tok in Name.Class or tok in Name.Builtin or tok in Name.Tag:
            return "tp"
        if tok in Keyword:
            return "kw"
        if tok in Name.Function or tok in Name.Decorator:
            return "fn"
        return None
    from pygments.token import Error
    text = pre.get_text()
    tokens = list(lex(text, get_lexer_by_name(lang)))
    if any(tok in Error for tok, _ in tokens):
        return                       # not valid <lang> (prose, transcripts): leave it plain
    out = []
    for tok, val in tokens:
        c = cls(tok)
        out.append(f'<span class="{c}">{esc(val)}</span>' if c and val.strip() else esc(val))
    code = "".join(out)
    if code.endswith("\n") and not text.endswith("\n"):
        code = code[:-1]
    pre.clear()
    pre.append(BeautifulSoup(code, "html.parser"))


def syntax(pre):
    for span in pre.find_all("span"):
        cls = (span.get("class") or [""])[0]
        if cls in SYNTAX:
            span["class"] = [SYNTAX[cls]]
        else:
            span.unwrap()


def wrap_text(soup, tag, nodes):
    """Group loose inline nodes into a <p> so nothing is left floating."""
    p = soup.new_tag(tag)
    for n in nodes:
        p.append(n.extract())
    return p


